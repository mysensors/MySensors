/**
 * @brief Command strobes for the CC1101 chip
 */
typedef enum cc1101Commands_e {
	CC1101_CMD_SRES = 0x30,    //!< Reset chip.
	CC1101_CMD_SFSTXON = 0x31, //!< Calibrate frequency synthesizer, go to wait state.
	CC1101_CMD_SXOFF = 0x32,   //!< Turn off crystal oscillator.
	CC1101_CMD_SCAL = 0x33,    //!< Calibrate frequency synthesizer, then turn off.
	CC1101_CMD_SRX = 0x34,     //!< Enable RX.
	CC1101_CMD_STX = 0x35,     //!< Enable TX.
	CC1101_CMD_SIDLE = 0x36,   //!< Exit TX/RX, go to idle.
	CC1101_CMD_SWOR = 0x38,    //!< Start wake-on-radio.
	CC1101_CMD_SPWD = 0x39,    //!< Enter power down mode.
	CC1101_CMD_SFRX = 0x3A,    //!< Flush RX FIFO.
	CC1101_CMD_SFTX = 0x3B,    //!< Flush TX FIFO.
	CC1101_CMD_SWORRST = 0x3C, //!< Reset RTC.
	CC1101_CMD_SNOP = 0x3D,    //!< No-op.
} cc1101_commands_t;

